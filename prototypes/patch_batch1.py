import openpyxl
from openpyxl.styles import Font, PatternFill

PATH = "prototypes/results/2026-09-19_shag4_partiya1_silnye.xlsx"
wb = openpyxl.load_workbook(PATH)
ws = wb["Партия 1 - сильные"]

green = PatternFill(start_color="D9EAD3", end_color="D9EAD3", fill_type="solid")
orange = PatternFill(start_color="FCE5CD", end_color="FCE5CD", fill_type="solid")

def set_row(r, code, name, chelch, crew, note):
    ws.cell(r, 5, code)
    ws.cell(r, 6, name)
    ws.cell(r, 7, chelch)
    ws.cell(r, 8, crew)
    ws.cell(r, 11, note)
    for c in range(1, 12):
        ws.cell(r, c).fill = green

rows_by_code = {}
for row_idx in range(2, ws.max_row + 1):
    rows_by_code[ws.cell(row_idx, 2).value] = row_idx

# Row 6: ГЭСН09-02-009-06 - по вашей просьбе, точный код
r = rows_by_code['ГЭСН09-02-009-06']
set_row(r, 'Н-11-02-002-01-01', 'Установка коробов понтона, вместимость резервуара: 200-300 м3',
        '23,5', 'Монтажник конструкций 3 разр. x2; Монтажник конструкций 4 разр. x1; Монтажник конструкций 6 разр. x1',
        'Правка 19.09 по вашей просьбе: код Н-11-02-002 вместо Н-11-02-001, состав звена тот же')

# Row 9: коррекция названия профессии, кандидат тот же
r = rows_by_code['ГЭСН23-01-001-02']
ws.cell(r, 8, 'Бетонщик 2 разр. x1')
ws.cell(r, 11, 'Правка 19.09: профессия исправлена на Бетонщик по вашему комментарию (в ФРСН значилось "Каменщик")')
for c in range(1, 12):
    ws.cell(r, c).fill = green

# Row 13, 20, 22, 24: чисто машинные нормы - состав звена не применяется
machine_only = ['ГЭСН01-01-009-08', 'ГЭСН01-01-022-07', 'ГЭСН01-01-022-08', 'ГЭСН01-02-003-01']
for code in machine_only:
    r = rows_by_code[code]
    ws.cell(r, 7, '-')
    ws.cell(r, 8, 'не применимо (чисто машинная норма)')
    ws.cell(r, 11, 'Уточнено 19.09: проверил по ФРСН и по смете - у этой позиции ведущий ресурс машина '
                   '(экскаватор/каток), в норме ФРСН нет ни одной строки состава звена вообще (все прочерки). '
                   'Состав звена для расчёта длительности не нужен, брать маш-ч напрямую из сметы.')
    for c in range(1, 12):
        ws.cell(r, c).fill = orange

# Row 27: арматура = рабочая (не запорная), найден корректный кандидат
r = rows_by_code['ГЭСН06-17-002-01']
set_row(r, 'Н-07-02-023-15-01 (диапазон 13..18)',
        'Установка и вязка арматуры отдельными стержнями, конструкции - ленточные фундаменты, прогоны, ригели',
        '18,5 (зависит от диаметра, см. диапазон)', 'Арматурщик 2 разр. x1; Арматурщик 5 разр. x1',
        'Решено 19.09: старый кандидат был про запорную арматуру (трубопроводную), а не про арматуру-каркас. '
        'По смете это точно арматурный каркас фундамента (Фундамент ленточный / Устройство фундамента). '
        'Верный сборник - Н-07-02-023, подсемейство "ленточные фундаменты" (шифры 13-18, отличаются диаметром '
        'прутка). Состав звена везде одинаковый: арматурщик 2 разр. + арматурщик 5 разр.')

# Row 28: маляр, но точного совпадения по контексту не нашлось - предлагаем ближайший вариант
r = rows_by_code['ГЭСНм39-01-001-19']
set_row(r, 'Н-31-07-002-01-01 (приблизительно, см. примечание)',
        'Окраска чугунных перил: очистка от ржавчины стальной щеткой поверхности перил',
        '1,3 (не совпадает по масштабу, см. примечание)', 'Маляр 2 разр. x1',
        'НЕ РЕШЕНО ПОЛНОСТЬЮ 19.09: вы правы, во всех найденных нормах "очистка щётками" состав звена - '
        '1 маляр (это устойчиво). Но точного аналога по контексту (очистка оборудования резервуара перед '
        'контролем качества сварки) в ФРСН нет - есть только "перила", "мосты", "балконные экраны". '
        'Предлагаю состав звена "Маляр 2 разр. x1" считать решённым, а код нормы (для чел-ч) считать условным. '
        'Если знаете лучший аналог по своему опыту - напишите, заменю.')

# Row 29: генератор пены, правильный код найден
r = rows_by_code['ГЭСНм12-08-005-09']
set_row(r, 'Н-11-01-009-01-01', 'Установка пеногенератора, вместимость резервуара: 100-400 м3',
        '5,7', 'Монтажник конструкций 3 разр. x1; Монтажник конструкций 5 разр. x2',
        'Решено 19.09: старый кандидат был про монтаж дизель-генератора (не связано). Правильная норма - '
        'из того же сборника 11, что и понтон, называется "Установка пеногенератора". Взял бракет по объёму '
        'резервуара 100-400 м3 - если ваш резервуар другого объёма, есть ещё 2 бракета (700-1000 и 2000-50000 м3), скажите, поправлю.')

# Rows 31, 33, 34: закладные детали - бетонщик/монтажник семья
r31 = rows_by_code['ГЭСН06-03-004-11']
set_row(r31, 'Н-07-02-010-01-01', 'Установка стальных закладных деталей в опалубку, масса до 4 кг, с вырезкой и заделкой отверстий',
        '0,67', 'Арматурщик 4 разр. x1; Плотник 3 разр. x1',
        'Решено 19.09: правильный сборник 07 (монолитный ж/б), не 43 (электромонтаж). Профессии - арматурщик '
        '+ плотник (не бетонщик в чистом виде, но это стандартная бригада для закладных в опалубку)')

r33 = rows_by_code['ГЭСН06-03-004-12']
set_row(r33, 'Н-07-02-010-03-01', 'Установка стальных закладных деталей в опалубку, масса до 20 кг, с вырезкой и заделкой отверстий',
        '0,77', 'Арматурщик 4 разр. x1; Плотник 3 разр. x1',
        'Решено 19.09: тот же сборник 07, следующий вес. Старый кандидат был из сборника 25 (кладка печей) - '
        'совпадение чисто текстовое, профессия "Трубоклад" была ошибкой.')

r34 = rows_by_code['ГЭСН06-03-004-13']
set_row(r34, 'Н-07-02-010-05-01', 'Установка стальных закладных деталей в опалубку, масса до 60 кг, с вырезкой и заделкой отверстий',
        '1', 'Арматурщик 4 разр. x1; Плотник 3 разр. x1',
        'Применил ту же логику, что и для строки выше (06-03-004-12), вы её не заполняли - проверьте, '
        'пожалуйста, отдельно. Ближайший вес.брекет "до 60 кг" - у ГЭСН это "свыше 20 кг" без верхней границы.')

wb.save(PATH)
print("Патч применён")

